# This endpoint is used to view the details of a specific patient based on their ID. It takes a patient_id as a path parameter, loads all the patient data using the load_data() function, and checks if the provided patient_id exists in the data. If it does, it returns the details of that patient; otherwise, it raises an HTTPException with a 404 status code indicating that the patient was not found.
@app.get('/patient/{patient_id}')
def view_paient(patient_id : str = Path(... , description= 'ID of the patient in DB' , example= 'P003')):
    #load all the patients
    data = load_data()

    if patient_id in data:
        return data[patient_id]
    raise HTTPException(status_code=404 , detail= 'Patient not found')

@app.get('/sort')
def sort_patients(sort_by : str = Query(..., description = ' Sort on the basis of height , weight and bmi') , order : str = Query('asc' ,  description = ' Sort in ascendeng or descending order')):
 
    valid_fields = ['height' , 'weight' , 'bmi']

    if sort_by not in valid_fields:
        raise HTTPException(status_code=400 , detail =f'Invalid sort field select from {valid_fields}')

    if order not in ['asc' , 'desc']:
        raise HTTPException(status_code=400 , detail = 'Invalid sort order select from asc or desc')
    
    data = load_data()
    sort_order = True if order == 'desc' else False

    sorted_data = sorted(data.values() , key = lambda x : x.get(sort_by , 0) , reverse=sort_order)

    return sorted_data



