# Use of BaseModel for data validation and serialization
# Use of Field for adding metadata and validation constraints to model fields   
# Use of computed_field for defining properties that are automatically calculated based on other fields in the model
# Use of Annotated for adding metadata to fields in a more concise way
# Use of Literal for defining fields that can only take specific literal values


from fastapi import FastAPI , Path , HTTPException , Query
from fastapi.responses import JSONResponse
from pydantic import BaseModel , Field, computed_field
from typing import Annotated , Literal
import json

app= FastAPI()

class Patient(BaseModel):

    # Annotated fields with descriptions and examples for better documentation in FastAPI. The Field function is used to provide additional metadata for each field, such as descriptions, examples, and validation constraints. This enhances the API documentation generated by FastAPI and helps users understand the expected input for each field.
    id: Annotated[str , Field(... , description= 'Unique patient identifier' , example = 'P001')]
    name: Annotated[str , Field(... , max_length=100, description="Full name of the patient, max 100 characters")]
    city: Annotated[str , Field(... , description= 'City of residence' , example = 'Gurgaon')]
    age: Annotated[int , Field(... , gt=0 , lt=120, description="Age of the patient and  must be between 1 and 120")]
    gender: Annotated[ Literal['male' , 'female' , 'other'] , Field(... , description= 'Gender of the patient' , example = 'male')]
    height: Annotated[float , Field(... , description= 'Height of the patient in centimeters' , example = 172.5)]
    weight: Annotated[float , Field(... , gt=0, description="Weight of the patient in kilograms and must be greater than zero" , example = 75.2)]

    # Here we are using computed_field decorator to calculate the BMI of a patient based on their weight and height. The BMI is calculated using the formula: weight (kg) / (height (m) ^ 2). The computed_field decorator allows us to define a property that is automatically calculated based on other fields in the model.
    @computed_field
    @property
    def bmi(self) -> float:
        bmi = round(self.weight/(self.height/100)**2,2)
        return bmi
    
    # Computed field for BMI category and what it does is to categorize the BMI of a patient into different categories such as Underweight, Normal weight, Overweight, and Obese based on the calculated BMI value. This provides additional information about the patient's health status based on their BMI.
    @computed_field
    @property
    def bmi_category(self) -> str:
        if self.bmi < 18.5:
            return 'Underweight'
        elif 18.5 <= self.bmi < 25:
            return 'Normal weight'
        elif 25 <= self.bmi < 30:
            return 'Overweight'
        else:
            return 'Obese'


